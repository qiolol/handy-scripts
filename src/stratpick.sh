# Returns whether the file given in `$1` looks like it's of the format we want
function right_format()
{
    if [[ -v FORMAT_AUDIO ]]
    then
        is_audio "${1}"
    elif [[ -v FORMAT_VIDEO ]]
    then
        is_video "${1}"
    else
        return 1
    fi
}

# Warns about any broken links at any level (`-L`) throughout `TOPLEVEL_DIR`
function warn_broken_links()
{
    local -a BROKEN=()
    mapfile -d '' -t BROKEN < <(
        find -L "${TOPLEVEL_DIR}" \
            -type l \
            -print0
    )
    if (( ${#BROKEN[@]} ))
    then
        printf 'Broken link warning: %s\n' "${BROKEN[@]}" >&2
    fi
}

# Builds a stratum as a global array from an array accessed via nameref in `$1`
# and populates `STRATA_NAMES` with the new stratum's name, generated using the
# stratum index in `$2`
function build_stratum()
{
    local FILE_ARR_NAME="$1"
    local INDEX="$2"
    local -n FILE_ARR="$FILE_ARR_NAME"

    declare -g -a "STRATUM_$INDEX" # Create the stratum as a global array.
    declare -n REF="STRATUM_$INDEX"
    REF=("${FILE_ARR[@]}") # Fill the stratum from the given array of files.
    unset -n REF
    unset -n FILE_ARR

    STRATA_NAMES+=("STRATUM_$INDEX")
}

# Constructs the strata whose files to sample from the (possibly symlink) files
# and directories directly inside `TOPLEVEL_DIR`
#
# See the example in `print_usage()`.
#
# Since we can't have an array of arrays in Bash, this creates a separate global
# array per stratum with generated names like "STRATUM_0", "STRATUM_1", etc. One
# more global array, `STRATA_NAMES`, is created. To iterate over the strata,
# iterate over `STRATA_NAMES` and, for each name, use a nameref (`declare -n`)
# to reference the stratum with that name:
# ```
# local STRATUM_NAME
# local -n REF
# local i=0
# for STRATUM_NAME in "${STRATA_NAMES[@]}"
# do
#     declare -n REF="$STRATUM_NAME" # Re-establish the nameref
#     printf 'Stratum %d (%s): %d file(s)\n' "$i" "$STRATUM_NAME" "${#REF[@]}"
#     printf '   %s\n' "${REF[@]}"
#     unset -n REF # Unbind the nameref for safety
#     (( i++ ))
# done
# ```
function build_strata()
{
    local -a TMP_ARR=() # Scratch array for building each stratum
    local INDEX=0 # Index baked into the generated name for each stratum

    # Optionally, clean up arrays left over from a hypothetical, previous call:
    local NAME
    for NAME in "${STRATA_NAMES[@]}"; do
        unset "$NAME"
    done
    STRATA_NAMES=() # The global array holding the names of all strata

    # First, warn about any broken links.
    warn_broken_links

    # Create the stratum of the top-level files of `TOPLEVEL_DIR`.
    #
    # `mapfile` runs `find` (with support for symlinks) and loads its
    # NUL-separated list into `TMP_ARR`.
    mapfile -d '' -t TMP_ARR < <(
        find -L "${TOPLEVEL_DIR}" \
            -maxdepth 1 \
            -type f \
            -print0
    )
    if (( ${#TMP_ARR[@]} ))
    then
        build_stratum TMP_ARR "$INDEX"
        INDEX=$((INDEX + 1))
    fi

    # Then create one stratum per immediate subdirectory of `TOPLEVEL_DIR`.
    local -a SUBDIRS=()
    mapfile -d '' -t SUBDIRS < <(
        find -L "${TOPLEVEL_DIR}" \
            -mindepth 1 -maxdepth 1 \
            -type d \
            -print0
    )

    local SUBDIR
    for SUBDIR in "${SUBDIRS[@]}"
    do
        mapfile -d '' -t TMP_ARR < <(
            find -L "${SUBDIR}" \
                -type f \
                -print0
        )
        if (( ${#TMP_ARR[@]} ))
        then
            build_stratum TMP_ARR "$INDEX"
            INDEX=$((INDEX + 1))
        fi
    done
}

# Returns whether the file given in `$1` is inside the array given in `$2`
function contains()
{
    local NEEDLE="$1"
    local -n HAYSTACK="$2"

    local FILE
    for FILE in "${HAYSTACK[@]}"
    do
        [[ "$FILE" == "$NEEDLE" ]] && return 0
    done
    return 1
}

# Prints the requested number of files (of the requested format) to stdout,
# returning non-zero when there was a problem doing so
function stratpick()
{
    local -a FILES=()
    local -A SEEN=() POS=()

    # Identify the strata in the `TOPLEVEL_DIR`.
    build_strata
    if (( ${#STRATA_NAMES[@]} == 0 ))
    then
        return 1
    fi

    # First, clean up the set of files to select from.
    #
    # In each stratum, keep only files of the right format, shuffle the files,
    # and drop strata that contain no files of the right format entirely.
    local -a LIVE=()
    local STRATUM_NAME F
    for STRATUM_NAME in "${STRATA_NAMES[@]}"
    do
        # ShellCheck issues a false positive SC2178 warning on these, thinking
        # `REF` is an array which is being assigned the string `$STRATUM_NAME`.
        # shellcheck disable=SC2178
        local -n REF="$STRATUM_NAME"
        local -a KEEP=() SHUFFLED=()
        for F in "${REF[@]}"
        do
            if right_format "$F"
            then
                KEEP+=("$F")
            fi
        done
        if (( ${#KEEP[@]} ))
        then
            mapfile -d '' -t SHUFFLED < <(printf '%s\0' "${KEEP[@]}" | shuf -z)
            REF=("${SHUFFLED[@]}")
            LIVE+=("$STRATUM_NAME")
        fi
        unset -n REF
    done

    # Pick random files from each stratum until we hit the requested number or
    # we run out of files.
    #
    # Each pass gives every remaining stratum one turn, in random order, and
    # strata drop out once they're exhausted. Shuffling the order means that,
    # when the final pass can't give every remaining stratum a turn, which
    # stratum gets that last turn is random rather than always being the first
    # stratum in `STRATA_NAMES`.
    while (( ${#FILES[@]} < FILES_TO_GET && ${#LIVE[@]} > 0 ))
    do
        local -a ORDER=() NEXT_LIVE=()
        mapfile -t ORDER < <(printf '%s\n' "${LIVE[@]}" | shuf)
        for STRATUM_NAME in "${ORDER[@]}"
        do
            (( ${#FILES[@]} == FILES_TO_GET )) && break

            # shellcheck disable=SC2178
            local -n REF="$STRATUM_NAME"
            local I=${POS[$STRATUM_NAME]:-0} CANDIDATE REAL
            # Take this stratum's next file, skipping any already picked.
            #
            # A stratum is only in `LIVE` while it still has unvisited files
            # (`I < ${#REF[@]}`).
            while (( I < ${#REF[@]} ))
            do
                CANDIDATE=${REF[I]}
                I=$(( I + 1 ))
                REAL=$(realpath -- "$CANDIDATE")
                if [[ -z ${SEEN[$REAL]+set} ]]
                then
                    SEEN[$REAL]=1
                    FILES+=("$CANDIDATE")
                    break
                fi
            done
            POS[$STRATUM_NAME]=$I
            if (( I < ${#REF[@]} ))
            then
                # The stratum still has files left; put it in `NEXT_LIVE`.
                NEXT_LIVE+=("$STRATUM_NAME")
            fi
            unset -n REF
        done
        LIVE=("${NEXT_LIVE[@]}")
    done

    # Report what files we've found.
    if (( ${#FILES[@]} ))
    then
        printf '%s\n' "${FILES[@]}"
    fi

    # Report whether we found the number of files requested.
    if (( ${#FILES[@]} < FILES_TO_GET ))
    then
        return 1
    fi
    return 0
}

if ! parse_arguments "${@}"
then
    print_usage

    exit 1
fi

stratpick
