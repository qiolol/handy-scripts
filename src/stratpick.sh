#!/bin/bash
# Returns a list of files via "stratified random selection" (stratified by
# directory)! Use this to generate playlists where shows with 1,000 episodes
# don't end up dominating most of the list.
#
# See the example in `print_usage()` for an overview.
#
# For handy ways to use this (assuming it's `stratpick` on your `PATH`), edit
# your `~/.bashrc`:
# ```
# alias randshows="stratpick v 25 \${SHOWS} | mpv --playlist=- &>/dev/null &"
#
# function randsongs()
# {
#   if (( ${#} != 1 ))
#   then
#     echo "From which directory?"
#     return 1
#   fi
#   stratpick a 25 "${1}" | mpv --playlist=- &>/dev/null &
# }
# ```
# Then you can use it like this:
# ```
# $ randshows
# $ randsongs "~/Music/Rush"
# ```
# The playlist generated by `randshows`, for example, will be a fairer version
# of that generated by
# `mpv --directory-filter-types=video --autocreate-playlist=filter --shuffle`
# because each show subdirectory in your `${SHOWS}` directory will be fairly
# represented across all 25 episodes selected.

function print_usage()
{
    echo -e "\
USAGE
\t${0} <a|v> <n> <dir>

DESCRIPTION
\tReturns a number of files of some format from the given directory via
\tdirectory-stratified random selection

\t\"Directory-stratified random selection\" means that, unlike randomly picking
\t'n' files from 'find dir -type f', files are sampled \"fairly\" from every
\tsubdirectory of 'dir' (arbitrarily-many levels deep) as well as from the files
\tdirectly inside of 'dir'.

\tFor example, take this directory hierarchy:

\tdir/
\t├── toplevelfile0.mp3
\t├── toplevelfile1.mp3
\t├── red
\t│   └── red0.mp3
\t└── blue
\t    ├── blue0.mp3
\t    ├── blue1.mp3
\t    ├── blue2.mp3
\t    ├── blue3.mp3
\t    ├── blue4.mp3
\t    ├── blue5.mp3
\t    ├── blue6.mp3
\t    ├── blue7.mp3
\t    ├── blue8.mp3
\t    └── subdir
\t        └── subdir0.mp3

\tRequesting 4 files from 'dir' will return those files from each of the 3
\t\"strata\" in the hierarchy:

\t\tStratum 1: The files directly inside 'dir' ('toplevelfile*.mp3')
\t\tStratum 2: The single file in 'red/'
\t\tStratum 3: The files in 'blue/' and 'blue/subdir/'

\tThe subdirectories of 'dir/', and the files directly in 'dir/', are treated as
\t\"strata\" from which to randomly pick files. This way, the files in 'blue/'
\tdo not dominate the selection despite being the most numerous. Of the 4 files
\treturned, 2 files will necessarily be from the same stratum. However, that
\tstratum won't be 'red/' since it only has one file (repeated paths are not
\tallowed in the output).

\tWhen requesting fewer files than there are strata, the strata that get skipped
\tare chosen at random.

\tThis is handy to get a \"fairly\" random playlist of files without having
\tfolders with more files dominate the playlist.

\tLinks are supported, too, so you can use this with \"playlist directories\"
\tfilled with links as an alternative to traditional playlist files.

PARAMETERS
\tREQUIRED
\t\ta|v\tWhat kind of files to get ('a' for audio or 'v' for video)

\t\tn\tThe number of files to get

\t\tdir\tThe directory to return files from" >&2
}

function parse_arguments()
{
    local -r REQUIRED_ARGS=3

    if (( ${#} != REQUIRED_ARGS ))
    then
        return 1
    fi

    local -r FORMAT_ARG="${1}"
    if ! [[ "${FORMAT_ARG}" =~ ^(a|v)$ ]]
    then
        return 1
    else
        if [[ "${FORMAT_ARG}" == "a" ]]
        then
            readonly FORMAT_AUDIO=1
        else
            readonly FORMAT_VIDEO=1
        fi
    fi

    FILES_TO_GET=${2}
    if ! [[ "${FILES_TO_GET}" =~ ^[[:digit:]]+$ ]]
    then
        return 1
    fi

    TOPLEVEL_DIR="${3}"
    if ! [[ -d "${TOPLEVEL_DIR}" ]]
    then
        return 1
    fi

    return 0
}

